"""Assemble the corpus data card from generated artifacts.

Owner: Samrat. Step A4 (completion).

Reads:  raw/SOURCE.md, derived/slice.sha256, derived/category_audit.json
Writes: docs/data_card.md   -- source/version, license, encoding + whitespace/Unicode handling,
                               split usage, slice rule, count, checksum, category statistics
"""
from __future__ import annotations

import json
from pathlib import Path

from ..config import DERIVED_DIR, DOCS_DIR, RAW_DIR, Config, load_config

WHITESPACE_NOTE = (
    "Each raw dataset row is used verbatim from `raw/wikitext-2/<split>.raw`. The only "
    "transformation before noise/tokenization is `str.strip()` on the line (removes the "
    "leading space and trailing ` \\n` that WikiText rows carry). No characters inside the "
    "line are altered. WikiText's literal `<unk>` strings and its spaced punctuation "
    "(`don 't`, ` , `) are left as-is. Encoding is UTF-8 end to end; non-ASCII code points "
    "(counted in the audit below) are preserved."
)


def _slice_meta() -> dict:
    text = (DERIVED_DIR / "slice.sha256").read_text(encoding="utf-8")
    meta = {"sha256": "", "selection_rule": "", "count": ""}
    for line in text.splitlines():
        if line.strip().endswith("slice.jsonl"):
            meta["sha256"] = line.split()[0]
        elif line.startswith("selection_rule:"):
            meta["selection_rule"] = line.split(":", 1)[1].strip()
        elif line.startswith("count:"):
            meta["count"] = line.split(":", 1)[1].strip()
    return meta


def write_data_card(cfg: Config | None = None, path: Path | str | None = None) -> Path:
    cfg = cfg or load_config()
    path = Path(path or DOCS_DIR / "data_card.md")

    source_md = (RAW_DIR / "SOURCE.md").read_text(encoding="utf-8")
    slice_meta = _slice_meta()
    audit = json.loads((DERIVED_DIR / "category_audit.json").read_text(encoding="utf-8"))

    cat_rows = "\n".join(
        f"| {cat} | {audit['by_category'][cat]:,} | {audit['shares'][cat]:.4f} |"
        for cat in audit["by_category"]
    )

    path.write_text(
        f"""# Corpus Data Card — WikiText-2 slice

_Generated by `src.corpus.datacard.write_data_card` from `raw/SOURCE.md`,
`derived/slice.sha256`, and `derived/category_audit.json`._

## Source
{source_md}

## Encoding, whitespace, and Unicode handling
{WHITESPACE_NOTE}

## Split usage
- Developed on: `{cfg.corpus_split}` (all noise/tokenizer development)
- Validation: reserved for sanity checks only; not used to tune any setting in Phase 1
- Test: not inspected

## Slice
- Selection rule: {slice_meta['selection_rule']}
- Length band: {cfg.slice_min_chars}–{cfg.slice_max_chars} characters (after `strip()`)
- Example count: {slice_meta['count']}
- Slice file: `derived/slice.jsonl`
- SHA-256 of slice file: `{slice_meta['sha256']}`

## Character-category statistics (slice)
{audit['n_examples']} examples · {audit['total_characters']:,} characters ·
{audit['non_ascii_characters']} non-ASCII code points

| Category | Count | Share |
|---|---|---|
{cat_rows}
""",
        encoding="utf-8",
    )
    return path


def main() -> None:
    print(write_data_card())


if __name__ == "__main__":
    main()
