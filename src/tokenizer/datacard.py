"""Emit the tokenizer data card.

Owner: Student B. Step B2.

Writes docs/tokenizer_card.md from the live tokenizer plus a checksum of its vocab file.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

import transformers

from ..config import DOCS_DIR
from .wrapper import TokenizerWrapper

BPE_VS_WORDPIECE = (
    "BPE grows its vocabulary by repeatedly merging the most frequent adjacent symbol pair "
    "(pure frequency). WordPiece instead adds the merge that most increases the training "
    "corpus likelihood under a unigram language model (a likelihood/association score, "
    "roughly `count(ab) / (count(a) * count(b))`), not raw frequency alone. BERT's WordPiece "
    "marks every non-word-initial subword with a leading `##`."
)


def _vocab_file(tok) -> Path | None:
    for name in ("vocab_file", "vocab_files_names"):
        val = getattr(tok, name, None)
        if isinstance(val, str) and Path(val).is_file():
            return Path(val)
    files = tok.save_vocabulary(str(DOCS_DIR))  # returns tuple of written paths
    return Path(files[0]) if files else None


def write_card(wrapper: TokenizerWrapper | None = None, path: Path | str | None = None) -> Path:
    wrapper = wrapper or TokenizerWrapper()
    path = Path(path or DOCS_DIR / "tokenizer_card.md")
    tok = wrapper.tokenizer
    summary = wrapper.config_summary()

    vocab_path = _vocab_file(tok)
    vocab_sha = (
        hashlib.sha256(vocab_path.read_bytes()).hexdigest() if vocab_path else "unavailable"
    )

    specials = "\n".join(f"| `{t}` | {i} |" for t, i in summary["special_token_ids"].items())
    sample = tok.tokenize("Robustness under character noise.")

    path.write_text(
        f"""# Tokenizer Data Card

_Generated by `src.tokenizer.datacard.write_card`._

## Checkpoint
- Model checkpoint: `{summary['checkpoint']}`
- Pinned revision hash: `{summary['revision']}`
- Tokenizer class: `{summary['tokenizer_class']}` (WordPiece)
- Rationale: fixed pretrained tokenizer (not trained on course data) so the clean and noisy
  branches are guaranteed identical and results stay comparable to the wider literature.

## Library
- `transformers` version: {transformers.__version__}

## Normalization / casing
- `do_lower_case`: {summary['do_lower_case']}
- `do_basic_tokenize`: {summary['do_basic_tokenize']}
- `strip_accents`: {summary['strip_accents']}  (None => follows `do_lower_case`)
- `tokenize_chinese_chars`: {summary['tokenize_chinese_chars']}
- `is_fast`: {summary['is_fast']}
- BERT `BasicTokenizer` cleans control chars, normalizes whitespace, and splits on punctuation
  before WordPiece is applied.

## Special tokens
| Token | ID |
|---|---|
{specials}

## Vocabulary
- Vocab size: {summary['vocab_size']}
- Vocab file: `{vocab_path.name if vocab_path else 'unavailable'}`
- SHA-256 of vocab file: `{vocab_sha}`

## Length
- `model_max_length`: {summary['model_max_length']}
- Project uses `max_length` = {wrapper.max_length}; the `truncated` flag is recorded per example.

## Sanity check
`tokenize("Robustness under character noise.")` -> `{sample}`

## BPE vs WordPiece
{BPE_VS_WORDPIECE}
""",
        encoding="utf-8",
    )
    return path


def main() -> None:
    print(write_card())


if __name__ == "__main__":
    main()
